#include "frame.hpp"

//-----------------------------------------------------------------------------
// Constructors
//-----------------------------------------------------------------------------

Frame::Frame(uint32_t w, uint32_t h, uint32_t ch) {
	resize(w, h, ch);
}

//-----------------------------------------------------------------------------
// Destructor
//-----------------------------------------------------------------------------

Frame::~Frame() {
	
}

//-----------------------------------------------------------------------------
// Public API
//-----------------------------------------------------------------------------

void
Frame::resize(uint32_t w, uint32_t h, uint32_t ch) {

	const uint64_t size = uint64_t(w) * ch * h;

	if (m_size < size) {
		m_size = size;
		m_data.reset(new uint8_t[size]);
	}

	m_w = w;
	m_h = h;
	m_ch = ch;
	m_stride = w * ch;
}
